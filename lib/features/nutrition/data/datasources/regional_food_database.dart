  static RegionalFoodItem? findClosestMatch(String query) {
    if (query.isEmpty) return null;
    final lower = query.toLowerCase();

    for (final item in items) {
      if (lower.contains(item.nameEn.toLowerCase()) ||
          lower.contains(item.nameRegional) ||
          item.nameEn.toLowerCase().contains(lower)) {
        return item;
      }
    }

    final words = lower.split(RegExp(r'\s+'));
    for (final word in words) {
      if (word.length >= 3) {
        for (final item in items) {
          if (item.nameEn.toLowerCase().contains(word)) {
            return item;
          }
        }
      }
    }
    return null;
  }
